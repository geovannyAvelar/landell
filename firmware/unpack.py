#!/usr/bin/env python3
"""Unpack a UV-K5 .packed.bin into a raw image for landell.

Usage: unpack.py in.packed.bin out.bin
Inverse of egzumer's fw-pack.py: check CRC16/XMODEM, undo the XOR, drop the
16-byte version string stored at offset 0x2000.
"""
import sys
from itertools import cycle

OBFUSCATION = bytes([
    0x47, 0x22, 0xC0, 0x52, 0x5D, 0x57, 0x48, 0x94, 0xB1, 0x60, 0x60, 0xDB, 0x6F, 0xE3, 0x4C, 0x7C,
    0xD8, 0x4A, 0xD6, 0x8B, 0x30, 0xEC, 0x25, 0xE0, 0x4C, 0xD9, 0x00, 0x7F, 0xBF, 0xE3, 0x54, 0x05,
    0xE9, 0x3A, 0x97, 0x6B, 0xB0, 0x6E, 0x0C, 0xFB, 0xB1, 0x1A, 0xE2, 0xC9, 0xC1, 0x56, 0x47, 0xE9,
    0xBA, 0xF1, 0x42, 0xB6, 0x67, 0x5F, 0x0F, 0x96, 0xF7, 0xC9, 0x3C, 0x84, 0x1B, 0x26, 0xE1, 0x4E,
    0x3B, 0x6F, 0x66, 0xE6, 0xA0, 0x6A, 0xB0, 0xBF, 0xC6, 0xA5, 0x70, 0x3A, 0xBA, 0x18, 0x9E, 0x27,
    0x1A, 0x53, 0x5B, 0x71, 0xB1, 0x94, 0x1E, 0x18, 0xF2, 0xD6, 0x81, 0x02, 0x22, 0xFD, 0x5A, 0x28,
    0x91, 0xDB, 0xBA, 0x5D, 0x64, 0xC6, 0xFE, 0x86, 0x83, 0x9C, 0x50, 0x1C, 0x73, 0x03, 0x11, 0xD6,
    0xAF, 0x30, 0xF4, 0x2C, 0x77, 0xB2, 0x7D, 0xBB, 0x3F, 0x29, 0x28, 0x57, 0x22, 0xD6, 0x92, 0x8B,
])
VERSION_OFFSET = 0x2000
VERSION_LEN = 16


def crc16_xmodem(data):
    crc = 0
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    packed, tail = data[:-2], data[-2:]
    if crc16_xmodem(packed).to_bytes(2, "little") != tail:
        sys.exit("CRC mismatch: not a packed UV-K5 image")
    plain = bytes(a ^ b for a, b in zip(packed, cycle(OBFUSCATION)))
    version = plain[VERSION_OFFSET:VERSION_OFFSET + VERSION_LEN]
    raw = plain[:VERSION_OFFSET] + plain[VERSION_OFFSET + VERSION_LEN:]
    open(sys.argv[2], "wb").write(raw)
    print(f"version: {version.rstrip(bytes(1)).decode('ascii', 'replace')}")
    print(f"sp=0x{int.from_bytes(raw[0:4], 'little'):08x} reset=0x{int.from_bytes(raw[4:8], 'little'):08x} size={len(raw)}")


main()
